export function getProduct(id: string) {
  return products.find((p) => p.id === id)
}

export function relatedProducts(product_: Product, limit = 4) {
  const sameClub = products.filter(
    (p) => p.club === product_.club && p.sport === product_.sport && p.id !== product_.id,
  )
  const sameSport = products.filter(
    (p) =>
      p.sport === product_.sport &&
      p.category === product_.category &&
      p.id !== product_.id &&
      p.club !== product_.club,
  )
  return [...sameClub, ...sameSport].slice(0, limit)
}

export function collectionProducts(collection: string) {
  return products.filter((p) => p.collections.includes(collection))
}

/** Leads with one product per sport so cross-sport rails stay varied. */
export function diverseBySport(list: Product[], limit: number) {
  const seen = new Set<string>()
  const lead: Product[] = []
  const rest: Product[] = []
  for (const item of list) {
    if (seen.has(item.sport)) rest.push(item)
    else {
      seen.add(item.sport)
      lead.push(item)
    }
  }
  return [...lead, ...rest].slice(0, limit)
}
