import { SIZES, type ProductType, type Size, type SportId } from '@/lib/constants'

export type ProductCategory = 'club' | 'national' | 'retro' | 'player' | 'training' | 'lifestyle'

export type Product = {
  id: string
  name: string
  club: string
  season: string
  category: ProductCategory
  type: ProductType
  sport: SportId
  audience: 'men' | 'women' | 'unisex'
  price: number
  originalPrice?: number
  colorway: Colorway
  pattern: JerseyPattern
  mediaKind?: 'jersey' | 'textile'
  badge?: 'new' | 'sale' | 'limited' | 'archive' | 'bestseller'
  sizes: Size[]
  availableSizes: Size[]
  rating: number
  reviews: number
  description: string
  features: string[]
  personalizationAvailable: boolean
  collections: string[]
  releaseDate: string
  soldOut?: boolean
  number?: string
}

const ALL_SIZES: Size[] = [...SIZES]

type Seed = Omit<
  Product,
  | 'sizes'
  | 'availableSizes'
  | 'audience'
  | 'sport'
  | 'pattern'
  | 'rating'
  | 'reviews'
  | 'features'
  | 'personalizationAvailable'
  | 'collections'
  | 'releaseDate'
> &
  Partial<
    Pick<
      Product,
      | 'availableSizes'
      | 'pattern'
      | 'audience'
      | 'sport'
      | 'rating'
      | 'reviews'
      | 'features'
      | 'personalizationAvailable'
      | 'collections'
      | 'releaseDate'
    >
  >

function product(seed: Seed): Product {
  const soldOut = seed.soldOut ?? false
  return {
    audience: 'unisex',
    sport: 'football',
    pattern: 'plain',
    rating: 4.6,
    reviews: 40,
    features: [
      'Engineered knit body with ventilation zones',
      'Woven club crest and heat-applied kit marks',
      'Ribbed collar with taped inner neck',
      'Regular fit — take your usual size',
    ],
    personalizationAvailable: seed.category !== 'retro' && seed.category !== 'lifestyle',
    collections: [],
    releaseDate: '2026-07-01',
    soldOut,
    sizes: ALL_SIZES,
    availableSizes: soldOut ? [] : ALL_SIZES.filter((s) => s !== 'XS'),
    ...seed,
  }
}

